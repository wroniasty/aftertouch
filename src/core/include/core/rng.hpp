struct RngStream {
    uint8_t seed      = 0;
    uint8_t xor_key   = 0;
    uint8_t xor_index = 0;
    uint8_t _pad      = 0;  // unique-object-representation pad

    // Map a 32-bit engine seed into the 16 bits the stream can use.
    // Upper 16 bits are IGNORED, not mixed — documented deliberately.
    constexpr void Seed(uint32_t s) {
        seed      = static_cast<uint8_t>(s & 0xFFu);
        xor_index = static_cast<uint8_t>((s >> 8) & 0xFFu);
        xor_key   = kRandomTable[xor_index];
        _pad      = 0;
    }

    constexpr uint8_t Draw() {
        if (seed == 0) {
            xor_index = static_cast<uint8_t>(xor_index + 1);
            xor_key   = kRandomTable[xor_index];
        }
        const uint8_t out = static_cast<uint8_t>(kRandomTable[seed] ^ xor_key);
        seed = static_cast<uint8_t>(seed + 1);
        return out;
    }
};

static_assert(sizeof(RngStream) == 4);
static_assert(std::has_unique_object_representations_v<RngStream>);

